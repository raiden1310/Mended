// Development-only check. Uses the existing fictional customer and supplied resized JPEGs.
import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {randomUUID} from 'node:crypto';
import {ConvexHttpClient} from 'convex/browser';
import {api} from '../convex/_generated/api.js';
const paths=process.argv.slice(2);
if(paths.length!==3)throw new Error('Pass three resized JPEG paths; the third is the hallmark.');
const client=new ConvexHttpClient('https://cool-hawk-741.convex.cloud');
const [customer]=await client.query(api.customers.search,{text:'Olivia'});assert.ok(customer);
const issuedDate=new Date().toISOString().slice(0,10);
const begin={requestId:randomUUID(),customerId:customer.id,expected:2,issuedDate};
const id=await client.mutation(api.combinedTickets.begin,begin);
assert.equal(await client.mutation(api.combinedTickets.begin,begin),id);
await assert.rejects(client.mutation(api.combinedTickets.finish,{id}));
const item={id,position:0,details:{itemType:'Bracelet',metals:[{metal:'Yellow gold',purity:'18K / 750',hallmark:'750'}],stones:['Unknown']},repairs:[{damage:'Bent band',serviceCode:'BG-03',photo:1,metalIndexes:[0],override:100,extra:5}],photos:paths.map((path,index)=>({data:`data:image/jpeg;base64,${readFileSync(path).toString('base64')}`,hallmark:index===2})),rush:true,rhodium:false,dueDate:issuedDate};
await assert.rejects(client.action(api.combinedTickets.addItem,{...item,photos:item.photos.slice(0,2)}));
const first=await client.action(api.combinedTickets.addItem,item);
assert.equal(await client.action(api.combinedTickets.addItem,item),first);
await assert.rejects(client.mutation(api.combinedTickets.finish,{id}));
await client.action(api.combinedTickets.addItem,{...item,position:1,repairs:[{...item.repairs[0],extra:12}],dueDate:new Date(Date.now()+86400000).toISOString().slice(0,10)});
await client.mutation(api.combinedTickets.finish,{id});
const ticket=await client.query(api.combinedTickets.get,{id});assert.equal(ticket.total,317);
const items=await client.query(api.combinedTickets.items,{id,after:-1});assert.equal(items.length,2);assert.equal(items[0].total,155);assert.equal(items[1].total,162);assert.notEqual(items[0].dueDate,items[1].dueDate);assert.equal(items[0].photos.length,3);
const signature=[[{x:.1,y:.1},{x:.3,y:.2}]];
await client.mutation(api.combinedTickets.sign,{id,signature});
await assert.rejects(client.mutation(api.combinedTickets.updateDue,{id:first,dueDate:issuedDate}));
assert.deepEqual((await client.query(api.combinedTickets.get,{id})).signature,signature);
console.log('Passed: two independently priced items, per-item rush/extra fees and dates, retry without duplicates, $317 combined total, one immutable signed ticket.');
process.exit(0);
